// Writes the live built-guide list the sitemap function ships with.
// Run before `astro build`. A guide added under src/data/routes is picked up on the next build.
// Guides that exist only as live D1 rows are added at request time, not here.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { liveBuiltGuides } from '../src/lib/live-guides.js';

const guides = await liveBuiltGuides();
const body = `// Generated by scripts/write-built-guides.mjs. Do not edit.
// Live guides from src/data/routes. functions/sitemap.xml.js merges D1 rows with status live.
export default ${JSON.stringify(guides, null, 2)};
`;

await writeFile(path.join(process.cwd(), 'functions/_lib/built-guides.js'), body);
console.log(`wrote ${guides.length} built guides`);
