// Writes the live built-guide list the sitemap function ships with.
// Run before `astro build`. A guide added under src/data/routes is picked up on the next build.
// Guides that exist only as live D1 rows are added at request time, not here.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { liveBuiltGuideIndex, liveBuiltGuides } from '../src/lib/live-guides.js';

function generated(note, value) {
  return `// Generated by scripts/write-built-guides.mjs. Do not edit.
${note}
export default ${JSON.stringify(value, null, 2)};
`;
}

const guides = await liveBuiltGuides();
const index = await liveBuiltGuideIndex();

await writeFile(
  path.join(process.cwd(), 'functions/_lib/built-guides.js'),
  generated('// Live guides from src/data/routes. functions/sitemap.xml.js merges D1 rows with status live.', guides),
);
await writeFile(
  path.join(process.cwd(), 'functions/_lib/built-guide-index.js'),
  generated('// Live built guides for /guides/. functions/guides/[[path]].js merges live D1 rows on top.', index),
);
console.log(`wrote ${guides.length} built guides`);
